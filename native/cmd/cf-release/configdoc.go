// cf-release config-doc (B760): scripts/gen-config-doc.mjs in Go, so the maintainer check needs no
// Node. It renders docs/reference/config.md from schema/code-forge.schema.json with the script's
// walk, labels and sentences; `--check` compares the file on disk with it.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const cdUsage = "usage: cf-release config-doc [--check]"

func configDocMain(a *app, args []string, root string) int {
	check := false
	for _, arg := range args {
		if arg != "--check" {
			a.err(cdUsage + "\n")
			return 2
		}
		check = true
	}
	generated, err := cdRender(root)
	if err != nil {
		a.err("config-doc: " + err.Error() + "\n")
		return 1
	}
	out := filepath.Join(root, "docs", "reference", "config.md")
	if !check {
		if err := os.WriteFile(out, []byte(generated), 0o644); err != nil {
			a.err("config-doc: " + err.Error() + "\n")
			return 1
		}
		a.out("wrote docs/reference/config.md\n")
		return 0
	}
	data, err := os.ReadFile(out)
	if err != nil {
		a.err("config-doc --check: docs/reference/config.md does not exist\n")
		return 1
	}
	if string(data) == generated {
		a.out("config-doc --check: docs/reference/config.md is up to date\n")
		return 0
	}
	disk, gen := strings.Split(string(data), "\n"), strings.Split(generated, "\n")
	i := 0
	for i < len(disk) && i < len(gen) && disk[i] == gen[i] {
		i++
	}
	line := func(lines []string) string {
		if i < len(lines) {
			return jsQuote(lines[i])
		}
		return `"<eof>"`
	}
	a.err(fmt.Sprintf("config-doc --check: docs/reference/config.md is stale (first difference at line %d)\n  on disk:    %s\n  generated:  %s\n", i+1, line(disk), line(gen)))
	return 1
}

// cdRender returns the exact bytes docs/reference/config.md should hold.
func cdRender(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "schema", "code-forge.schema.json"))
	if err != nil {
		return "", err
	}
	parsed, err := jsParse(string(data))
	if err != nil {
		return "", err
	}
	schema, ok := parsed.(*jsObject)
	if !ok {
		return "", fmt.Errorf("schema/code-forge.schema.json is not an object")
	}
	defs, _ := cdField(schema, "$defs").(*jsObject)
	var rows [][5]string
	cdWalk(schema, "", defs, &rows)
	lines := []string{
		"# `.code-forge.yml` configuration reference",
		"",
		"Generated by `sh scripts/cf-release.sh config-doc` from `schema/code-forge.schema.json` — do not hand-edit this file. " +
			"Run `sh scripts/cf-release.sh config-doc --check` in CI to catch a schema change that was not followed by a regeneration.",
		"",
	}
	if d, ok := cdField(schema, "description").(string); ok {
		lines = append(lines, d, "")
	}
	lines = append(lines, cdRequiredSentence(schema, defs), "",
		"Every other key defaults as shown, or is entirely absent from a minimal file. "+
			"`additionalProperties: false` applies everywhere a key set is fixed; the rows marked "+
			"`<key>` are the handful of open-ended maps where the schema accepts a caller-chosen name "+
			"(a question id, a level name, a key name, a provider id).",
		"",
		"| Key | Type | Required | Default | Notes |",
		"|---|---|---|---|---|")
	for _, r := range rows {
		lines = append(lines, fmt.Sprintf("| `%s` | %s | %s | %s | %s |", r[0], r[1], r[2], r[3], strings.ReplaceAll(r[4], "|", `\|`)))
	}
	lines = append(lines, "")
	return strings.Join(lines, "\n"), nil
}

// cdField is node[key] for an object node, else nil.
func cdField(node any, key string) any {
	if o, ok := node.(*jsObject); ok {
		v, _ := o.get(key)
		return v
	}
	return nil
}

func cdHas(node any, key string) bool {
	if o, ok := node.(*jsObject); ok {
		_, has := o.get(key)
		return has
	}
	return false
}

// cdResolve is resolveRef: the $defs entry a $ref names, else the node itself.
func cdResolve(node any, defs *jsObject) any {
	if ref, ok := cdField(node, "$ref").(string); ok {
		parts := strings.Split(ref, "/")
		if defs == nil {
			return nil
		}
		v, _ := defs.get(parts[len(parts)-1])
		return v
	}
	return node
}

func cdIsObject(node any) bool {
	switch node.(type) {
	case *jsObject, []any:
		return true
	}
	return false
}

func cdTypeLabel(in any, defs *jsObject) string {
	node := cdResolve(in, defs)
	if !cdIsObject(node) {
		return "unknown"
	}
	if cdHas(node, "const") {
		return "const `" + jsStringify(cdField(node, "const"), "") + "`"
	}
	if enum, ok := cdField(node, "enum").([]any); ok {
		parts := make([]string, len(enum))
		for i, v := range enum {
			parts[i] = "`" + jsTemplate(v, true) + "`"
		}
		return "enum: " + strings.Join(parts, ", ")
	}
	if anyOf, ok := cdField(node, "anyOf").([]any); ok {
		parts := make([]string, len(anyOf))
		for i, sub := range anyOf {
			parts[i] = cdTypeLabel(sub, defs)
		}
		return strings.Join(parts, ` \| `)
	}
	typ := cdField(node, "type")
	if typ == "array" {
		return "array<" + cdTypeLabel(cdField(node, "items"), defs) + ">"
	}
	if list, ok := typ.([]any); ok {
		parts := make([]string, len(list))
		for i, v := range list {
			if v != nil {
				parts[i] = jsTemplate(v, true)
			}
		}
		return strings.Join(parts, ` \| `)
	}
	if s, ok := typ.(string); ok {
		return s
	}
	return "object"
}

func cdDefaultLabel(in any, defs *jsObject) string {
	node := cdResolve(in, defs)
	if cdHas(node, "default") {
		return "`" + jsStringify(cdField(node, "default"), "") + "`"
	}
	return "—"
}

func cdNotesLabel(in any, defs *jsObject) string {
	node := cdResolve(in, defs)
	var parts []string
	for _, f := range [][2]string{{"minimum", "min "}, {"maximum", "max "}, {"exclusiveMinimum", "> "}, {"minLength", "minLength "}, {"minItems", "minItems "}} {
		if cdHas(node, f[0]) {
			parts = append(parts, f[1]+jsTemplate(cdField(node, f[0]), true))
		}
	}
	if d, ok := cdField(node, "description").(string); ok {
		parts = append(parts, d)
	}
	return strings.Join(parts, "; ")
}

func cdBacktickList(keys []string) string {
	quoted := make([]string, len(keys))
	for i, k := range keys {
		quoted[i] = "`" + k + "`"
	}
	if len(quoted) <= 1 {
		return strings.Join(quoted, "")
	}
	return strings.Join(quoted[:len(quoted)-1], ", ") + " and " + quoted[len(quoted)-1]
}

func cdStrings(v any) []string {
	list, _ := v.([]any)
	out := make([]string, 0, len(list))
	for _, e := range list {
		out = append(out, jsTemplate(e, true))
	}
	return out
}

func cdRequiredSentence(schema *jsObject, defs *jsObject) string {
	required := cdStrings(cdField(schema, "required"))
	if len(required) == 0 {
		return "No top-level key is required by the schema."
	}
	var noDefault, withDefault []string
	for _, key := range required {
		prop := cdResolve(cdField(cdField(schema, "properties"), key), defs)
		if prop == nil || !cdHas(prop, "default") {
			noDefault = append(noDefault, key)
		} else {
			withDefault = append(withDefault, key)
		}
	}
	be := "are"
	if len(required) == 1 {
		be = "is"
	}
	sentence := cdBacktickList(required) + " " + be + " required."
	if len(noDefault) > 0 {
		have, it := "have", "any of them"
		if len(noDefault) == 1 {
			have, it = "has", "it"
		}
		sentence += " " + cdBacktickList(noDefault) + " " + have + " no schema-level default; a config omitting " + it + " is refused."
	}
	if len(withDefault) > 0 {
		have := "have"
		if len(withDefault) == 1 {
			have = "has"
		}
		sentence += " " + cdBacktickList(withDefault) + " " + have + " a schema-level default, so omitting it is not itself refused."
	}
	return sentence
}

// cdWalk is the script's depth-first walk over properties and typed additionalProperties, in the
// schema file's key order.
func cdWalk(in any, path string, defs *jsObject, rows *[][5]string) {
	node := cdResolve(in, defs)
	if !cdIsObject(node) {
		return
	}
	switch cdField(node, "type") {
	case "object":
		required := map[string]bool{}
		for _, k := range cdStrings(cdField(node, "required")) {
			required[k] = true
		}
		if props, ok := cdField(node, "properties").(*jsObject); ok {
			for _, key := range props.keys {
				child := props.vals[key]
				childPath := key
				if path != "" {
					childPath = path + "." + key
				}
				req := ""
				if required[key] {
					req = "yes"
				}
				*rows = append(*rows, [5]string{childPath, cdTypeLabel(child, defs), req, cdDefaultLabel(child, defs), cdNotesLabel(child, defs)})
				cdWalk(child, childPath, defs, rows)
			}
		}
		if ap := cdField(node, "additionalProperties"); cdIsObject(ap) {
			childPath := "<key>"
			if path != "" {
				childPath = path + ".<key>"
			}
			notes := "user-defined key"
			if n := cdNotesLabel(ap, defs); n != "" {
				notes += "; " + n
			}
			*rows = append(*rows, [5]string{childPath, cdTypeLabel(ap, defs), "", cdDefaultLabel(ap, defs), notes})
			cdWalk(ap, childPath, defs, rows)
		}
	case "array":
		if items := cdField(node, "items"); items != nil {
			cdWalk(items, path+"[]", defs, rows)
		}
	}
}
