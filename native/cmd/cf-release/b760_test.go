func b760Run(t *testing.T, root string, args ...string) (int, string, string) {
	t.Helper()
	var out, errb bytes.Buffer
	code := run(newApp(&out, &errb), args, root)
	return code, out.String(), errb.String()
}

func b760Write(t *testing.T, path, text string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}

// The labels, walk order and sentences of scripts/gen-config-doc.mjs (its output for this schema).
const b760Schema = `{"description":"Top text.","type":"object","required":["version","provider"],
"properties":{
 "version":{"const":1,"description":"Schema version."},
 "provider":{"$ref":"#/$defs/prov","default":"anthropic"},
 "levels":{"type":"object","additionalProperties":{"type":"object","properties":{"model":{"type":"string","minLength":1}},"required":["model"]}},
 "n":{"type":["integer","null"],"minimum":0,"maximum":9,"default":null,"description":"a | b"},
 "list":{"type":"array","minItems":1,"items":{"type":"object","properties":{"x":{"anyOf":[{"type":"string"},{"$ref":"#/$defs/prov"}],"default":{"a":[1,"q"]}}}}}
},
"$defs":{"prov":{"enum":["anthropic","xai"],"default":"anthropic"}}}`

const b760Doc = "# `.code-forge.yml` configuration reference\n\n" +
	"Generated by `sh scripts/cf-release.sh config-doc` from `schema/code-forge.schema.json` — do not hand-edit this file. Run `sh scripts/cf-release.sh config-doc --check` in CI to catch a schema change that was not followed by a regeneration.\n\n" +
	"Top text.\n\n" +
	"`version` and `provider` are required. `version` has no schema-level default; a config omitting it is refused. `provider` has a schema-level default, so omitting it is not itself refused.\n\n" +
	"Every other key defaults as shown, or is entirely absent from a minimal file. `additionalProperties: false` applies everywhere a key set is fixed; the rows marked `<key>` are the handful of open-ended maps where the schema accepts a caller-chosen name (a question id, a level name, a key name, a provider id).\n\n" +
	"| Key | Type | Required | Default | Notes |\n|---|---|---|---|---|\n" +
	"| `version` | const `1` | yes | — | Schema version. |\n" +
	"| `provider` | enum: `anthropic`, `xai` | yes | `\"anthropic\"` |  |\n" +
	"| `levels` | object |  | — |  |\n" +
	"| `levels.<key>` | object |  | — | user-defined key |\n" +
	"| `levels.<key>.model` | string | yes | — | minLength 1 |\n" +
	"| `n` | integer \\| null |  | `null` | min 0; max 9; a \\| b |\n" +
	"| `list` | array<object> |  | — | minItems 1 |\n" +
	"| `list[].x` | string \\| enum: `anthropic`, `xai` |  | `{\"a\":[1,\"q\"]}` |  |\n"

// TestB760ConfigDocRendersTheSchema: `config-doc` writes the script's bytes, `--check` passes on
// them and names the first differing line otherwise.
func TestB760ConfigDocRendersTheSchema(t *testing.T) {
	root := t.TempDir()
	b760Write(t, filepath.Join(root, "schema", "code-forge.schema.json"), b760Schema)
	code, out, errText := b760Run(t, root, "config-doc", "--check")
	if code != 1 || out != "" || errText != "config-doc --check: docs/reference/config.md does not exist\n" {
		t.Fatalf("missing: %d %q %q", code, out, errText)
	}
	if err := os.MkdirAll(filepath.Join(root, "docs", "reference"), 0o755); err != nil {
		t.Fatal(err)
	}
	code, out, errText = b760Run(t, root, "config-doc")
	if code != 0 || out != "wrote docs/reference/config.md\n" || errText != "" {
		t.Fatalf("write: %d %q %q", code, out, errText)
	}
	data, err := os.ReadFile(filepath.Join(root, "docs", "reference", "config.md"))
	if err != nil || string(data) != b760Doc {
		t.Fatalf("doc:\n%s\nwant:\n%s", data, b760Doc)
	}
	if code, out, _ := b760Run(t, root, "config-doc", "--check"); code != 0 || out != "config-doc --check: docs/reference/config.md is up to date\n" {
		t.Fatalf("check: %d %q", code, out)
	}
	b760Write(t, filepath.Join(root, "docs", "reference", "config.md"), strings.Replace(b760Doc, "Top text.", "Old text.", 1))
	code, _, errText = b760Run(t, root, "config-doc", "--check")
	want := "config-doc --check: docs/reference/config.md is stale (first difference at line 5)\n  on disk:    \"Old text.\"\n  generated:  \"Top text.\"\n"
	if code != 1 || errText != want {
		t.Fatalf("stale: %d %q", code, errText)
	}
	if code, _, errText := b760Run(t, root, "config-doc", "--fix"); code != 2 || errText != cdUsage+"\n" {
		t.Fatalf("usage: %d %q", code, errText)
	}
}

