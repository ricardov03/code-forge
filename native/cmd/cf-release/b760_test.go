// TestB760BuildNativeHost: `build-native --host` builds only this machine's target, with no node.
func TestB760BuildNativeHost(t *testing.T) {
	root := t.TempDir()
	b760Write(t, filepath.Join(root, "package.json"), `{"name":"x","version":"1.2.3"}`)
	bin := t.TempDir()
	log := filepath.Join(bin, "calls.log")
	b760Write(t, filepath.Join(bin, "go"), "#!/bin/sh\necho \"$GOOS/$GOARCH $*\" >> '"+log+"'\n"+
		"while [ $# -gt 0 ]; do if [ \"$1\" = -o ]; then printf bin > \"$2\"; fi; shift; done\n")
	b760Write(t, filepath.Join(bin, "node"), "#!/bin/sh\ntouch '"+bin+"/node-ran'\n")
	for _, f := range []string{"go", "node"} {
		if err := os.Chmod(filepath.Join(bin, f), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("PATH", bin+":/usr/bin:/bin")
	arch := runtime.GOARCH
	if arch == "amd64" {
		arch = "x64"
	}
	target := runtime.GOOS + "-" + arch
	code, out, errText := b760Run(t, root, "build-native", "--host")
	if code != 0 || errText != "" || out != "native "+target+": 3 bytes (v1.2.3)\n" {
		t.Fatalf("%d %q %q", code, out, errText)
	}
	calls, _ := os.ReadFile(log)
	lines := strings.Split(strings.TrimSpace(string(calls)), "\n")
	if len(lines) != 2 || !strings.HasPrefix(lines[1], runtime.GOOS+"/"+runtime.GOARCH+" build ") {
		t.Fatalf("go calls: %q", calls)
	}
	if _, err := os.Stat(filepath.Join(root, "native", "bin", target, "code-forge-native")); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(bin, "node-ran")); err == nil {
		t.Fatal("build-native started node")
	}
	if code, _, errText := b760Run(t, root, "build-native", "--all"); code != 1 || errText != "build-native: usage: cf-release build-native [--host]\n" {
		t.Fatalf("usage: %d %q", code, errText)
	}
}
