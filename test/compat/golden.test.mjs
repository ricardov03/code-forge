import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

const root = fileURLToPath(new URL('../../', import.meta.url));
const golden = new URL('./golden/', import.meta.url);
const names = ['canon.json', 'ledger.json', 'sign.json', 'ticket.json'];
const entries = [...names, 'config'].sort();

test('golden files regenerated from Node equal all four committed files byte for byte', async () => {
  const committed = await readdir(golden).catch((err) => {
    if (err.code === 'ENOENT') return [];
    throw err;
  });
  assert.deepEqual(committed.sort(), entries, 'expected exactly four committed compatibility files and the config directory');
  const dir = await mkdtemp(path.join(os.tmpdir(), 'compat-golden-'));
  try {
    const result = spawnSync(process.execPath, [path.join(root, 'scripts/compat-golden.mjs'), dir], {
      cwd: dir, encoding: 'utf8', env: process.env,
    });
    assert.equal(result.status, 0, `Node generator failed: ${result.stderr}`);
    assert.deepEqual((await readdir(dir)).sort(), entries, 'generator must emit exactly four files and the config directory');
    for (const name of names) {
      assert.equal(await readFile(path.join(dir, name), 'utf8'), await readFile(new URL(name, golden), 'utf8'), `${name}: generated bytes drifted`);
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('golden boundary cases reject covered-field tampering and retain unsigned-field edits', async () => {
  const files = await readdir(golden).catch((err) => {
    if (err.code === 'ENOENT') return [];
    throw err;
  });
  assert.deepEqual(files.sort(), entries, 'boundary expectations require exactly four files and the config directory');
  const kit = JSON.parse(await readFile(new URL('sign.json', golden), 'utf8'));
  const { verifyRow } = await import('../../src/state/signer.mjs');
  const key = Buffer.from(kit.key_hex, 'hex');
  assert.equal(kit.verify.length, 8, 'expected eight valid/invalid MAC boundary cases');
  for (const c of kit.verify) assert.deepEqual(verifyRow(c.row, key), c.expected, c.name);
});
